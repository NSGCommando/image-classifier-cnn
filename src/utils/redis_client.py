# persistent Redis Client store
_RedisClientCache = {}

def get_redis(client_task_name:str):
    """
    Check if a redis client is cached or not.
    Return it if yes, else create and cache a new client and then return it
    """
    if client_task_name not in _RedisClientCache:
        redis_host = "redis_container" if os.environ.get("IS_DOCKER")=="1" else "localhost"
        _RedisClientCache[client_task_name] = redis.Redis(host=redis_host, 
                                                          port=6379, db=0,
                                                          # socker_timeout should be decently greater than the block time 
                                                          # in the worker's Xread/Xgroupreads or there's the chance of 
                                                          # redis stream connection drop
                                                          socket_timeout=15, 
                                                          socket_keepalive=True)
        # print(redis_client.connection_pool.connection_kwargs) # debug print statement to check connection args
    return _RedisClientCache[client_task_name]

